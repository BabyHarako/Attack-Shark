// Hypothesis: sending an 0x04-prefixed output report makes the device reply
// with an on-demand battery reading, instead of waiting for its own passive
// heartbeat. Grounded in real data (0x04 is confirmed as the real battery
// report type from passive captures) but the "you can request it" part is
// unverified — we specifically tested this failed with receiveFeatureReport
// earlier, so this is a different, still-unconfirmed approach.
function buildBatteryQueryCmd(){
  const body = [0x04,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00];
  const sum = body.reduce((a,x)=>a+x,0) & 0xFF;
  const chk = (0x4D - sum) & 0xFF;
  return [8, ...body, chk];
}
function getBatteryLevel(dev){
  return new Promise((resolve, reject) => {
    const timeout = setTimeout(() => {
      dev.removeEventListener('inputreport', handler);
      reject(new Error('Battery query timed out — device did not respond to the request'));
    }, 2000);
    function handler(e){
      const d = new Uint8Array(e.data.buffer);
      if(d[0] === 0x04){
        clearTimeout(timeout);
        dev.removeEventListener('inputreport', handler);
        resolve({ battery: d[5], rssi: d[8] });
      }
    }
    dev.addEventListener('inputreport', handler);
    const [rid, ...data] = buildBatteryQueryCmd();
    dev.sendReport(rid, new Uint8Array(data)).catch(err => {
      clearTimeout(timeout);
      dev.removeEventListener('inputreport', handler);
      reject(err);
    });
  });
}

// Hypothesis: per-DPI-stage RGB color is settable at address 0x2c + stageIndex*4.
// UNLIKE the battery query above, this has NO grounding in anything captured —
// we've never seen evidence the R11 Ultra supports custom per-stage DPI LED
// color at all. Treat this as a much shakier guess than the battery one.
function buildColorCmd(hex, stageIndex){
  const r = parseInt(hex.substr(1,2),16);
  const g = parseInt(hex.substr(3,2),16);
  const b = parseInt(hex.substr(5,2),16);
  const addr = 0x2c + (stageIndex * 4);
  const fieldChk = (0x55 - ((r+g+b) & 0xFF)) & 0xFF;
  const body = [0x07,0x00,0x00,addr,0x04,r,g,b,fieldChk,0,0,0,0,0,0];
  const sum = body.reduce((a,x)=>a+x,0) & 0xFF;
  const pktChk = (0x4D - sum) & 0xFF;
  return [8, ...body, pktChk];
}

