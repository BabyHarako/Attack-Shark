el('connectBtn').addEventListener('click', async () => {
  if(!('hid' in navigator)){
    alert('WebHID isn\'t available in this browser. Use Chrome or Edge on desktop, over HTTPS (or localhost).');
    return;
  }
  try{
    const devices = await navigator.hid.requestDevice({ filters: [] });
    if(!devices.length) return;

    let target = null;
    const opened = [];
    for(const d of devices){
      try{
        await d.open();
        opened.push(d);
        const supportsReport8 = d.collections.some(c =>
          c.outputReports && c.outputReports.some(r => r.reportId === 8)
        );
        if(supportsReport8 && !target) target = d;
      }catch(e){ /* skip */ }
    }
    if(!target){
      target = opened[0];
      logLine('in', 'warning: no collection advertised report ID 8 — using first available; sends may fail.');
    }
    device = target;

    // The mouse reports a DIFFERENT product ID depending on how it's
    // connected — confirmed via real USB capture: 0xfb44 = via the 2.4GHz
    // dongle, 0xfb43 = wired (USB-C cable direct). Both work identically
    // for every command in this tool; this just makes the label accurate.
    // 0xfb43 = wired, 0xfb44 = 2.4GHz dongle — both confirmed via real USB
    // captures. Anything else (e.g. Bluetooth direct pairing, which we
    // can't capture at the USB level to confirm) gets flagged honestly
    // rather than guessed at.
    let connType, connDetail;
    if(device.productId === 0xfb43){ connType = 'Wired'; connDetail = 'USB-C'; }
    else if(device.productId === 0xfb44){ connType = 'Wireless'; connDetail = '2.4GHz receiver'; }
    else { connType = 'Unknown mode'; connDetail = `pid=0x${device.productId.toString(16)} — possibly Bluetooth, unconfirmed`; }
    const isWired = device.productId === 0xfb43;

    statusDot.className = 'dot on';
    statusText.textContent = 'CONNECTED';
    el('connVal').textContent = connType;
    el('connSub').textContent = (device.productName || 'HID device') + ' · ' + connDetail;
    // Firmware version isn't queryable live — WebHID doesn't expose the
    // USB device descriptor's bcdDevice field, only vendorId/productId/
    // productName/collections. This value (2.02) is from a real capture
    // of your unit's descriptor, not a live read — won't auto-update if
    // you ever flash new firmware.
    el('fwVal').textContent = '2.02';
    el('fwSub').textContent = 'From USB descriptor (not live — see note)';
    el('batteryVal').textContent = 'reading…';
    saveBtn.disabled = false;
    el('connectBtn').textContent = 'Reconnect';

    el('sbDot').className = 'dot on';
    el('sbName').textContent = device.productName || 'Attack Shark Mouse';
    el('sbSub').textContent = `Attack Shark · ${connType}`;

    opened.forEach(d => {
      d.addEventListener('inputreport', e => {
        const hex = bytesToHex(e.data);
        logLine('in', `report ${e.reportId} · ${hex}`);
        const bytes = new Uint8Array(e.data.buffer || e.data);
        if(bytes.length >= 6 && bytes[0] === 0x04){
          const pct = bytes[5];
          if(pct >= 0 && pct <= 100){
            setBatteryBaseline(pct); // updates baseline + re-renders the smoothed estimate
          }
        }
      });
    });
    startBatteryTicker();

    // Try to force an immediate battery reading instead of waiting for the
    // next passive heartbeat push (which can take a few seconds).
    for(const d of opened){
      try{
        const result = await d.receiveFeatureReport(8);
        const bytes = new Uint8Array(result.buffer);
        if(bytes.length >= 6 && bytes[0] === 0x04){
          const pct = bytes[5];
          if(pct >= 0 && pct <= 100){
            setBatteryBaseline(pct);
            logLine('in', `active feature-report read succeeded — battery ${pct}%`);
          }
        }
      }catch(e){ /* expected to fail on most collections — ignore and wait for passive push */ }
    }

    // Second, independent attempt: send the confirmed-real battery-report
    // trigger byte and listen for the device's reply. Verified against an
    // actual USB capture (bytes and response offsets both match), so this
    // is a solid attempt at getting an immediate reading automatically
    // rather than waiting on the passive heartbeat.
    try{
      const result = await getBatteryLevel(device);
      if(result.battery >= 0 && result.battery <= 100){
        setBatteryBaseline(result.battery);
        logLine('in', `battery query succeeded automatically — ${result.battery}%`);
      }
    }catch(e){ /* will fall back to the passive heartbeat listener above */ }

    logLine('in', `opened "${device.productName}" — vid=0x${device.vendorId.toString(16)} pid=0x${device.productId.toString(16)} — ${opened.length} collection(s) live, report-8 support: yes`);
  }catch(err){
    statusDot.className = 'dot err';
    statusText.textContent = 'CONNECTION FAILED';
    el('sbDot').className = 'dot err';
    el('sbSub').textContent = 'Connection failed';
    logLine('in', `error: ${err.message}`);
  }
});


