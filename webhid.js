/* ---------------- Battery smoothing ----------------
   Pure client-side estimation from real device readings — no device
   commands involved. When a real battery % arrives from the mouse, we
   store it as a baseline with a timestamp; between readings (which can be
   sparse/irregular since we don't control the heartbeat interval), we
   interpolate a smooth estimate based on a conservative drain rate so the
   number doesn't just sit frozen or jump abruptly. Persisted across page
   reloads via localStorage (safe here — this is a standalone hosted page,
   not a sandboxed artifact). */
const BATTERY_STORAGE_KEY = 'r11ultra_battery_baseline';
const BATTERY_DRAIN_PCT_PER_HOUR = 0.3;
const BATTERY_MAX_DRIFT_PCT = 5;
let batteryBaseline = null;
let batteryTickHandle = null;
function loadBatteryBaseline(){
  try{
    const raw = localStorage.getItem(BATTERY_STORAGE_KEY);
    if(raw) batteryBaseline = JSON.parse(raw);
  }catch(e){}
}
function saveBatteryBaseline(){
  try{ localStorage.setItem(BATTERY_STORAGE_KEY, JSON.stringify(batteryBaseline)); }
  catch(e){}
}
function setBatteryBaseline(rawPct){
  const isNew = !batteryBaseline || batteryBaseline.raw !== rawPct;
  batteryBaseline = { raw: rawPct, ts: Date.now() };
  saveBatteryBaseline();
  renderBatteryDisplay();
  if(isNew) logLine('in', `battery baseline updated → ${rawPct}% (raw device read)`);
}
function estimateBatteryPct(){
  if(!batteryBaseline) return null;
  const hoursElapsed = (Date.now() - batteryBaseline.ts) / 3600000;
  const drift = Math.min(BATTERY_MAX_DRIFT_PCT, BATTERY_DRAIN_PCT_PER_HOUR * hoursElapsed);
  const est = batteryBaseline.raw - drift;
  return Math.max(0, Math.min(100, Math.round(est)));
}
function renderBatteryDisplay(){
  const pct = estimateBatteryPct();
  if(pct === null) return;
  el('batteryVal').textContent = `${pct}%`;

  // Matches the official app's own LED-indicator legend we captured
  // (Green ≥75%, Orange <75%, Red ≤15%) so the color reads consistently
  // with what the mouse's receiver LED itself would show.
  let color;
  if(pct <= 15) color = '#ff4a2e';
  else if(pct < 75) color = '#ffb020';
  else color = '#35d0c4';

  const fillWidth = Math.max(0, (pct / 100) * 25); // inner track is 25 units wide
  const fill = el('batteryFill');
  fill.style.width = `${fillWidth}px`;
  fill.setAttribute('width', fillWidth);
  fill.setAttribute('fill', color);
  el('batteryIcon').querySelector('rect[stroke]').setAttribute('stroke', pct <= 15 ? color : 'var(--dim)');
}
function startBatteryTicker(){
  if(batteryTickHandle) return;
  batteryTickHandle = setInterval(renderBatteryDisplay, 30000);
}

